/* ── PWA standalone: i link target="_blank" restano nella stessa finestra ──
   Quando l'app è installata (Aggiungi a schermata Home) e gira in standalone,
   target="_blank" / window.open aprono comunque una nuova scheda del browser
   con la barra URL, uscendo dalla modalità standalone. Qui si intercettano
   solo i link/aperture verso lo stesso dominio e si naviga nella stessa finestra. */
(function () {
  function isStandalonePwa() {
    return window.matchMedia('(display-mode: standalone)').matches || window.navigator.standalone === true;
  }
  if (!isStandalonePwa()) return;
  document.addEventListener('click', function (e) {
    var a = e.target.closest && e.target.closest('a[target="_blank"]');
    if (!a || !a.href) return;
    try {
      if (new URL(a.href, location.href).origin !== location.origin) return;
    } catch (err) { return; }
    e.preventDefault();
    location.href = a.href;
  }, true);
  var _origOpen = window.open;
  window.open = function (url, target) {
    if (url && (!target || target === '_blank')) {
      try {
        if (new URL(url, location.href).origin === location.origin) {
          location.href = url;
          return window;
        }
      } catch (err) {}
    }
    return _origOpen.apply(window, arguments);
  };
})();
